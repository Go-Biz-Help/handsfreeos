#!/usr/bin/env node
/**
 * The phone app's database schema, generated from the same source as the phone's contract and the sync scenarios:
 * every client table the Sync Streams fill (apps/sync/sync-config.yaml, read by apps/sync/src/shape.ts), each column
 * typed the way PowerSync types it on a phone, from the database types the contract records
 * (packages/core/test/contract/mobile-contract.json).
 *
 *   node scripts/mobile-schema.mjs           write apps/mobile/src/sync/schema.ts
 *   node scripts/mobile-schema.mjs --check   fail when it's out of date (the app's lint runs this, so CI does)
 *
 * It needs no database. The contract test holds the recorded types to the database, and the sync scenarios' phones
 * type their tables from the database through the same shape.ts, so the app, the scenarios and the contract can't
 * drift apart: a stream change the contract hasn't recorded fails here first.
 *
 * `--config`, `--contract` and `--out` point it at other files (the app's Jest test of this check uses them).
 *
 * shape.ts is TypeScript, so this runs under Node's type stripping (it restarts itself with the flag when Node needs
 * it) and resolves the extensionless imports the repo's TypeScript uses.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { registerHooks } from 'node:module';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const self = fileURLToPath(import.meta.url);
if (!process.features.typescript) {
  const run = spawnSync(
    process.execPath,
    [
      '--experimental-strip-types',
      '--disable-warning=ExperimentalWarning',
      self,
      ...process.argv.slice(2),
    ],
    { stdio: 'inherit' },
  );
  process.exit(run.status ?? 1);
}

const root = join(dirname(self), '..');
const argument = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i > 0 && process.argv[i + 1] ? resolve(process.argv[i + 1]) : fallback;
};
const CONFIG = argument('--config', join(root, 'apps/sync/sync-config.yaml'));
const CONTRACT = argument(
  '--contract',
  join(root, 'packages/core/test/contract/mobile-contract.json'),
);
const OUT = argument('--out', join(root, 'apps/mobile/src/sync/schema.ts'));

/** Local tables the app keeps beside the synced ones (M10 step 10): no stream may fill a table of the same name. */
const RESERVED = ['commands', 'outbox'];

// The repo's TypeScript imports its own files without an extension ('./schema/index'), which Node won't guess.
registerHooks({
  resolve(specifier, context, nextResolve) {
    if (
      /^\.\.?\//.test(specifier) &&
      !/\.[cm]?[jt]sx?$/.test(specifier) &&
      context.parentURL?.endsWith('.ts')
    ) {
      for (const suffix of ['.ts', '/index.ts']) {
        const url = new URL(specifier + suffix, context.parentURL);
        if (existsSync(fileURLToPath(url))) return nextResolve(url.href, context);
      }
    }
    return nextResolve(specifier, context);
  },
});

/** people → PeopleRow, workspace_access → WorkspaceAccessRow. */
const rowType = (table) => `${table.replace(/(^|_)([a-z])/g, (_, __, c) => c.toUpperCase())}Row`;

const TS_TYPE = { text: 'string', integer: 'number', real: 'number' };

/** What a column's value looks like on the phone, where that isn't plain from its SQLite type. */
function note(databaseType) {
  if (databaseType === 'boolean') return 'boolean in the database: 1 or 0 here';
  if (databaseType === 'json' || databaseType === 'jsonb') return `${databaseType}: JSON text here`;
  if (databaseType.endsWith('[]')) return `${databaseType}: a JSON array here`;
  if (databaseType.startsWith('timestamp')) return `${databaseType}: ISO 8601 text here`;
  return databaseType;
}

function renderSchema(tables) {
  for (const t of tables)
    if (RESERVED.includes(t.name))
      throw new Error(`A stream fills "${t.name}", a name the app keeps for its own local table.`);
  const lines = [
    '// Generated by scripts/mobile-schema.mjs from apps/sync/sync-config.yaml and the types the phone’s contract records',
    '// (packages/core/test/contract/mobile-contract.json). Don’t edit it: run `pnpm --filter @hfos/mobile schema`.',
    "import { column, Table } from '@powersync/common';",
    '',
    '/**',
    ' * Every table the Sync Streams fill on the phone, typed as PowerSync types them: whole numbers and booleans are',
    ' * integers, floats are reals, and everything else (uuids, times, numerics, JSON, arrays) is text. PowerSync adds',
    ' * `id` to each. A table with `workspace_id` is indexed on it, since one phone can keep several businesses.',
    ' * The app’s own local tables sit beside these in `app-schema.ts`.',
    ' */',
    'export const syncedTables = {',
  ];
  for (const t of tables) {
    const indexed = t.columns.some((c) => c.name === 'workspace_id');
    lines.push(`  /** ${t.streams.join(', ')} */`);
    lines.push(`  ${t.name}: new Table(`);
    lines.push('    {');
    for (const c of t.columns) lines.push(`      ${c.name}: column.${c.type},`);
    lines.push(indexed ? '    },' : '    }');
    if (indexed) lines.push("    { indexes: { workspace: ['workspace_id'] } },");
    lines.push('  ),');
  }
  lines.push('};', '');
  lines.push(
    '/*',
    ' * A row of each table, as a query gives it. Every column can be null on the phone (a row a stream sends without',
    ' * it, or an older row), so screens check before they use one.',
    ' */',
    '',
  );
  for (const t of tables) {
    lines.push(`/** A row of \`${t.name}\` (${t.streams.join(', ')}). */`);
    lines.push(`export interface ${rowType(t.name)} {`);
    lines.push('  readonly id: string;');
    for (const c of t.columns) {
      if (c.databaseType !== 'text') lines.push(`  /** ${note(c.databaseType)} */`);
      lines.push(`  readonly ${c.name}: ${TS_TYPE[c.type]} | null;`);
    }
    lines.push('}', '');
  }
  lines.push('/** Each synced table’s row type, by table name. */');
  lines.push('export interface SyncedRows {');
  for (const t of tables) lines.push(`  ${t.name}: ${rowType(t.name)};`);
  lines.push('}', '', 'export type SyncedTableName = keyof SyncedRows;', '');
  return lines.join('\n');
}

async function formatted(content, filepath) {
  const prettier = await import('prettier');
  const options = (await prettier.resolveConfig(filepath)) ?? {};
  return prettier.format(content, { ...options, filepath });
}

async function main() {
  const check = process.argv.includes('--check');
  const { clientTablesFromContract } = await import(
    pathToFileURL(join(root, 'apps/sync/src/shape.ts')).href
  );
  const recorded = JSON.parse(readFileSync(CONTRACT, 'utf8')).tables;
  let content;
  try {
    content = await formatted(
      renderSchema(clientTablesFromContract(recorded, readFileSync(CONFIG, 'utf8'))),
      OUT,
    );
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
  const rel = relative(root, OUT);
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
  if (current === content) {
    if (check) console.log('The phone app’s schema matches the sync streams and the contract.');
    return;
  }
  if (check) {
    console.error(
      `${rel} is out of date with apps/sync/sync-config.yaml and the phone’s contract.`,
    );
    console.error('Run `pnpm --filter @hfos/mobile schema` and commit the result.');
    process.exit(1);
  }
  writeFileSync(OUT, content);
  console.log(`wrote ${rel}`);
}

await main();
