#!/usr/bin/env node
/**
 * Writes local env files from `supabase status`. Local development only.
 *   .env.local          everything, for tests and tooling (includes the local secret key)
 *   apps/api/.env       API settings only (never a secret key)
 *   apps/worker/.env    worker settings (the only app allowed to hold the secret key)
 *   apps/web/.env.local publishable values only
 *   apps/extension/.env.local  where a build of the browser extension signs in (publishable values only)
 */
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

const env = { ...process.env };
const colimaSock = join(homedir(), '.colima/default/docker.sock');
if (!env.DOCKER_HOST && existsSync(colimaSock)) env.DOCKER_HOST = `unix://${colimaSock}`;

const raw = execFileSync('supabase', ['status', '-o', 'env'], { env, encoding: 'utf8' });
const vals = Object.fromEntries(
  raw
    .split('\n')
    .filter((l) => l.includes('='))
    .map((l) => {
      const i = l.indexOf('=');
      return [
        l.slice(0, i).trim(),
        l
          .slice(i + 1)
          .trim()
          .replace(/^"|"$/g, ''),
      ];
    }),
);
for (const k of ['API_URL', 'PUBLISHABLE_KEY', 'SECRET_KEY', 'DB_URL', 'MAILPIT_URL']) {
  if (!vals[k]) throw new Error(`supabase status did not return ${k}; is the local stack running?`);
}
const db = new URL(vals.DB_URL);
const dbHost = `${db.hostname}:${db.port}`;
const header =
  '# Generated by `pnpm env:local` from `supabase status`. Local development only. Do not commit.';

// Keep the worker's local encryption key across runs, or sealed test credentials stop opening. The Assistant's
// settings stay too, so a rerun doesn't quietly switch off a local Anthropic key someone pasted in.
const previousWorkerEnv = existsSync('apps/worker/.env')
  ? readFileSync('apps/worker/.env', 'utf8')
  : '';
const previous = (name) =>
  new RegExp(`^${name}=(.+)$`, 'm').exec(previousWorkerEnv)?.[1]?.trim() || '';
const encryptionKey = previous('WORKER_ENCRYPTION_KEY') || randomBytes(32).toString('base64');
const keep = (names) => names.flatMap((n) => (previous(n) ? [`${n}=${previous(n)}`] : []));
const assistantLines = keep([
  'ANTHROPIC_API_KEY',
  'ASSISTANT_MODEL',
  'AI_MODEL',
  'ASSISTANT_TOOL_SEARCH',
  'ASSISTANT_EFFORT',
  // The backup AI (OpenAI), the same way.
  'OPENAI_API_KEY',
  'OPENAI_MODEL',
  'OPENAI_ASSISTANT_MODEL',
  'OPENAI_VOICE_MODEL',
  'AI_ALERT_EMAILS',
]);
// A Deepgram key someone pasted in stays too, the same way: without it the worker falls back to the fake
// transcriber, and a rerun would quietly stop a local voicemail ever having words.
const transcriberLines = keep(['DEEPGRAM_API_KEY', 'TRANSCRIBER']);
// A real Stripe or Square app someone pasted in stays across runs, the way the Assistant's key does — and
// PAYMENTS_PROVIDER is left out when one is there, so the worker picks the real providers on its own.
const paymentLines = keep([
  'STRIPE_CLIENT_ID',
  'STRIPE_SECRET_KEY',
  'STRIPE_PUBLISHABLE_KEY',
  'STRIPE_WEBHOOK_SECRET',
  'STRIPE_PLATFORM_WEBHOOK_SECRET',
  'SQUARE_APPLICATION_ID',
  'SQUARE_APPLICATION_SECRET',
  'SQUARE_WEBHOOK_SIGNATURE_KEYS',
  'SQUARE_ENVIRONMENT',
]);

const write = (path, lines) => {
  writeFileSync(path, [header, ...lines, ''].join('\n'));
  console.log(`wrote ${path} (${lines.length} vars)`);
};

write('.env.local', [
  `SUPABASE_URL=${vals.API_URL}`,
  `SUPABASE_PUBLISHABLE_KEY=${vals.PUBLISHABLE_KEY}`,
  `SUPABASE_SECRET_KEY=${vals.SECRET_KEY}`,
  `SUPABASE_DB_URL=${vals.DB_URL}`,
  `DATABASE_URL=postgresql://hfos_api:hfos_api_dev_password@${dbHost}/postgres`,
  `DATABASE_URL_WORKER=postgresql://hfos_worker:hfos_worker_dev_password@${dbHost}/postgres`,
  `MAILPIT_URL=${vals.MAILPIT_URL}`,
  `SMTP_URL=smtp://${db.hostname}:54425`,
  `WEB_URL=http://localhost:3000`,
  `API_URL=http://127.0.0.1:4000`,
  `WORKER_URL=http://127.0.0.1:4100`,
]);
write('apps/api/.env', [
  'PORT=4000',
  'HOST=127.0.0.1',
  'LOG_LEVEL=debug',
  'WEB_ORIGINS=http://localhost:3000',
  `SUPABASE_URL=${vals.API_URL}`,
  `DATABASE_URL=postgresql://hfos_api:hfos_api_dev_password@${dbHost}/postgres`,
]);
write('apps/worker/.env', [
  'LOG_LEVEL=debug',
  'WORKER_POLL_MS=1000',
  `SUPABASE_URL=${vals.API_URL}`,
  `SUPABASE_SECRET_KEY=${vals.SECRET_KEY}`,
  `DATABASE_URL_WORKER=postgresql://hfos_worker:hfos_worker_dev_password@${dbHost}/postgres`,
  `SMTP_URL=smtp://${db.hostname}:54425`,
  'MAIL_FROM=HandsFreeOS <hello@handsfreeos.local>',
  'WEB_URL=http://localhost:3000',
  'WEB_ORIGINS=http://localhost:3000',
  'WORKER_HTTP_PORT=4100',
  'WORKER_PUBLIC_URL=http://127.0.0.1:4100',
  'TELEPHONY_PROVIDER=fake',
  'FAKE_APPROVAL_MS=3000',
  `WORKER_ENCRYPTION_KEY=${encryptionKey}`,
  // The website chat hashes visitors' IP addresses with this. A fixed value is fine on your own computer;
  // production refuses it.
  'CHAT_IP_KEY=local-chat-ip-key-for-development-only',
  // Cloudflare Turnstile's always-pass test secret: bookings and website chats run the human check the way they do
  // in production, through Cloudflare (so it needs the internet). Any token passes it. Production refuses it.
  'TURNSTILE_SECRET_KEY=1x0000000000000000000000000000000AA',
  // Taking money on your own computer: the stand-in provider, with its own payment page on the worker and
  // properly signed webhooks posted back to it. No Stripe or Square account is needed to run everything.
  // A bank transfer settles three seconds after it is paid, so the "Paying — expected by…" state is real.
  ...(paymentLines.length
    ? paymentLines
    : ['PAYMENTS_PROVIDER=fake', 'PAYMENTS_FAKE_SETTLE_MS=3000']),
  ...assistantLines,
  ...transcriberLines,
]);
write('apps/web/.env.local', [
  'NEXT_PUBLIC_API_URL=http://127.0.0.1:4000',
  'NEXT_PUBLIC_WORKER_URL=http://127.0.0.1:4100',
  `NEXT_PUBLIC_SUPABASE_URL=${vals.API_URL}`,
  `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${vals.PUBLISHABLE_KEY}`,
  'NEXT_PUBLIC_PASSKEYS_ENABLED=true',
  // The agency switch on Set up your business, which production hides. The browser tests sign agencies up with it.
  'NEXT_PUBLIC_AGENCY_SIGNUP_ENABLED=true',
  // The matching always-pass test site key (public). The worker names it too; this is the pages' fallback.
  'NEXT_PUBLIC_TURNSTILE_SITE_KEY=1x00000000000000000000AA',
]);
write('apps/extension/.env.local', [
  'HFOS_API_URL=http://127.0.0.1:4000',
  'HFOS_WORKER_URL=http://127.0.0.1:4100',
  'HFOS_WEB_URL=http://localhost:3000',
  `HFOS_SUPABASE_URL=${vals.API_URL}`,
  `HFOS_SUPABASE_PUBLISHABLE_KEY=${vals.PUBLISHABLE_KEY}`,
]);
