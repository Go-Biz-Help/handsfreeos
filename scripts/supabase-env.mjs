#!/usr/bin/env node
/**
 * Writes local env files from `supabase status`. Local development only.
 *   .env.local          everything, for tests and tooling (includes the local secret key)
 *   apps/api/.env       API settings only (never a secret key)
 *   apps/worker/.env    worker settings (the only app allowed to hold the secret key)
 *   apps/web/.env.local publishable values only
 */
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

const env = { ...process.env };
const colimaSock = join(homedir(), '.colima/default/docker.sock');
if (!env.DOCKER_HOST && existsSync(colimaSock)) env.DOCKER_HOST = `unix://${colimaSock}`;

const raw = execFileSync('supabase', ['status', '-o', 'env'], { env, encoding: 'utf8' });
const vals = Object.fromEntries(
  raw
    .split('\n')
    .filter((l) => l.includes('='))
    .map((l) => {
      const i = l.indexOf('=');
      return [
        l.slice(0, i).trim(),
        l
          .slice(i + 1)
          .trim()
          .replace(/^"|"$/g, ''),
      ];
    }),
);
for (const k of ['API_URL', 'PUBLISHABLE_KEY', 'SECRET_KEY', 'DB_URL', 'MAILPIT_URL']) {
  if (!vals[k]) throw new Error(`supabase status did not return ${k}; is the local stack running?`);
}
const db = new URL(vals.DB_URL);
const dbHost = `${db.hostname}:${db.port}`;
const header =
  '# Generated by `pnpm env:local` from `supabase status`. Local development only. Do not commit.';

// Keep the worker's local encryption key across runs, or sealed test credentials stop opening.
const previousWorkerEnv = existsSync('apps/worker/.env')
  ? readFileSync('apps/worker/.env', 'utf8')
  : '';
const encryptionKey =
  /^WORKER_ENCRYPTION_KEY=(.+)$/m.exec(previousWorkerEnv)?.[1]?.trim() ||
  randomBytes(32).toString('base64');

const write = (path, lines) => {
  writeFileSync(path, [header, ...lines, ''].join('\n'));
  console.log(`wrote ${path} (${lines.length} vars)`);
};

write('.env.local', [
  `SUPABASE_URL=${vals.API_URL}`,
  `SUPABASE_PUBLISHABLE_KEY=${vals.PUBLISHABLE_KEY}`,
  `SUPABASE_SECRET_KEY=${vals.SECRET_KEY}`,
  `SUPABASE_DB_URL=${vals.DB_URL}`,
  `DATABASE_URL=postgresql://hfos_api:hfos_api_dev_password@${dbHost}/postgres`,
  `DATABASE_URL_WORKER=postgresql://hfos_worker:hfos_worker_dev_password@${dbHost}/postgres`,
  `MAILPIT_URL=${vals.MAILPIT_URL}`,
  `SMTP_URL=smtp://${db.hostname}:54425`,
  `WEB_URL=http://localhost:3000`,
  `API_URL=http://127.0.0.1:4000`,
  `WORKER_URL=http://127.0.0.1:4100`,
]);
write('apps/api/.env', [
  'PORT=4000',
  'HOST=127.0.0.1',
  'LOG_LEVEL=debug',
  'WEB_ORIGINS=http://localhost:3000',
  `SUPABASE_URL=${vals.API_URL}`,
  `DATABASE_URL=postgresql://hfos_api:hfos_api_dev_password@${dbHost}/postgres`,
]);
write('apps/worker/.env', [
  'LOG_LEVEL=debug',
  'WORKER_POLL_MS=1000',
  `SUPABASE_URL=${vals.API_URL}`,
  `SUPABASE_SECRET_KEY=${vals.SECRET_KEY}`,
  `DATABASE_URL_WORKER=postgresql://hfos_worker:hfos_worker_dev_password@${dbHost}/postgres`,
  `SMTP_URL=smtp://${db.hostname}:54425`,
  'MAIL_FROM=HandsFreeOS <hello@handsfreeos.local>',
  'WEB_URL=http://localhost:3000',
  'WEB_ORIGINS=http://localhost:3000',
  'WORKER_HTTP_PORT=4100',
  'WORKER_PUBLIC_URL=http://127.0.0.1:4100',
  'TELEPHONY_PROVIDER=fake',
  'FAKE_APPROVAL_MS=3000',
  `WORKER_ENCRYPTION_KEY=${encryptionKey}`,
]);
write('apps/web/.env.local', [
  'NEXT_PUBLIC_API_URL=http://127.0.0.1:4000',
  'NEXT_PUBLIC_WORKER_URL=http://127.0.0.1:4100',
  `NEXT_PUBLIC_SUPABASE_URL=${vals.API_URL}`,
  `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${vals.PUBLISHABLE_KEY}`,
  'NEXT_PUBLIC_PASSKEYS_ENABLED=true',
]);
