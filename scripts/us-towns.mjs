#!/usr/bin/env node
/**
 * The US towns Social Outreach knows the places of, so Alignable's search can cover the towns within 25 miles of the
 * person's own (docs/outreach.md decision 115), generated from the US Census Bureau's Gazetteer of places (public
 * domain): every city, town, village, borough and census-designated place, at its middle.
 *
 *   node scripts/us-towns.mjs <2023_Gaz_place_national.txt>   write packages/core/src/addons/outreach/us-towns.ts
 *
 * The Gazetteer is at https://www.census.gov/geographies/reference-files/time-series/geo/gazetteer-files.html
 * ("Places", the national file, unzipped). Each town is kept as Alignable writes a town in its addresses, by its name
 * in lowercase with dashes ("round-rock" in "round-rock-tx"), and where it is to a hundredth of a degree, about half a
 * mile: enough for 25 miles. Two places of one name in a state are one town: the incorporated one, else the first.
 * A town that shares a government with its county goes by the town's own name (`KNOWN_AS`).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'packages/core/src/addons/outreach/us-towns.ts');
const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/us-towns.mjs <2023_Gaz_place_national.txt>');
  process.exit(1);
}

/** What the Gazetteer puts after a place's name: its kind ("Round Rock city", "The Woodlands CDP"). */
const KIND =
  /\s+(city and borough|consolidated government \(balance\)|metro(politan)? government \(balance\)|unified government \(balance\)|city \(balance\)|\(balance\)|metropolitan government|metro township|urban county|CDP|city|town|village|borough|municipality|township|corporation|county|government)$/i;
/** A census-designated place: a community with no town government of its own. */
const CDP = '57';
/**
 * Towns that share a government with their county, which the Gazetteer names for both ("Nashville-Davidson") but
 * everyone, Alignable too, calls by the town's own name: by state and the Gazetteer's name. Each takes the place of
 * any other place of that name in its state.
 */
const KNOWN_AS = {
  'ga athens-clarke-county': 'athens',
  'ga augusta-richmond-county': 'augusta',
  'ga cusseta-chattahoochee-county-unified': 'cusseta',
  'ga georgetown-quitman-county-unified': 'georgetown',
  'ga macon-bibb': 'macon',
  'hi urban-honolulu': 'honolulu',
  'id boise-city': 'boise',
  'ky lexington-fayette': 'lexington',
  'ky louisville-jefferson-county': 'louisville',
  'mt anaconda-deer-lodge': 'anaconda',
  'mt butte-silver-bow': 'butte',
  'tn hartsville-trousdale': 'hartsville',
  'tn lynchburg-moore-county': 'lynchburg',
  'tn nashville-davidson': 'nashville',
};

const slugOf = (name) =>
  name
    .replace(KIND, '')
    .trim()
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/['’.]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const [header, ...lines] = readFileSync(source, 'utf8').split(/\r?\n/);
const at = Object.fromEntries(header.split('\t').map((h, i) => [h.trim(), i]));
const states = new Map();
for (const line of lines) {
  const cells = line.split('\t');
  const state = cells[at.USPS]?.trim().toLowerCase();
  // Puerto Rico's places aren't on Alignable.
  if (!state || state === 'pr') continue;
  const named = slugOf(cells[at.NAME] ?? '');
  const slug = KNOWN_AS[`${state} ${named}`] ?? named;
  const lat = Math.round(Number(cells[at.INTPTLAT]) * 100);
  const lon = Math.round(Number(cells[at.INTPTLONG]) * 100);
  if (!slug || !Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  const towns = states.get(state) ?? new Map();
  states.set(state, towns);
  const had = towns.get(slug);
  // The best of two places of one name: a town known by it, then an incorporated place, then a CDP.
  const rank = slug !== named ? 0 : cells[at.LSAD] === CDP ? 2 : 1;
  if (!had || rank < had.rank) towns.set(slug, { lat, lon, rank });
}

const body = [...states.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([state, towns]) =>
      `  ${state}: '${[...towns.entries()]
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([slug, t]) => `${slug} ${t.lat} ${t.lon}`)
        .join('|')}',`,
  )
  .join('\n');
const count = [...states.values()].reduce((n, towns) => n + towns.size, 0);

const file = `/**
 * The US towns Social Outreach knows the places of (docs/outreach.md decision 115): ${count.toLocaleString('en-US')} cities, towns, villages,
 * boroughs and census-designated places, from the US Census Bureau's 2023 Gazetteer of places (public domain).
 * Generated by \`node scripts/us-towns.mjs\`: don't edit it by hand.
 *
 * Each state's towns, by its two letters: "<town> <latitude × 100> <longitude × 100>", the town as Alignable writes it
 * in its addresses ("round-rock" in "round-rock-tx"), separated by "|". Server-only: it's big, so ./ops/towns.ts reads
 * it and nothing the extension or the apps load does.
 */
export const US_TOWNS: Readonly<Record<string, string>> = {
${body}
};
`;
const options = (await prettier.resolveConfig(OUT)) ?? {};
writeFileSync(OUT, await prettier.format(file, { ...options, filepath: OUT }));
console.log(`Wrote ${relative(root, OUT)}: ${count.toLocaleString('en-US')} towns.`);
